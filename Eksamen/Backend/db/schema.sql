-- Set search path for roles
DO $$
DECLARE
    current_db TEXT;
BEGIN
    SELECT current_database() INTO current_db;
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_admin') THEN
        EXECUTE format('ALTER ROLE app_admin IN DATABASE %I SET search_path = app, public', current_db);
    END IF;
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_user') THEN
        EXECUTE format('ALTER ROLE app_user IN DATABASE %I SET search_path = app, public', current_db);
    END IF;
END$$;

-- Create app schema
CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION app_admin;
CREATE EXTENSION IF NOT EXISTS citext;

-- Create ENUM types
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'dep_status') THEN
    CREATE TYPE dep_status AS ENUM ('PLANNED','IN_PROGRESS','CANCELLED','DONE');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'delay_severity') THEN
    CREATE TYPE delay_severity AS ENUM ('INFO','MINOR','MAJOR');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'fare_type') THEN
    CREATE TYPE fare_type AS ENUM ('ADULT','STUDENT','SENIOR');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'ticket_state') THEN
    CREATE TYPE ticket_state AS ENUM ('NEW','USED','REFUNDED');
  END IF;
END$$;

-- role table
CREATE TABLE IF NOT EXISTS app.role (
  id           SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         TEXT NOT NULL UNIQUE CHECK (code ~ '^[A-Z_]+$'),
  description  TEXT
);

-- user table
CREATE TABLE IF NOT EXISTS app."user" (
  id             BIGSERIAL PRIMARY KEY,
  email          CITEXT NOT NULL UNIQUE,
  password_hash  TEXT NOT NULL,
  session_token  TEXT UNIQUE,
  full_name      TEXT NOT NULL,
  is_active      BOOLEAN NOT NULL DEFAULT true,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- user_role table
CREATE TABLE IF NOT EXISTS app.user_role (
  user_id     BIGINT    NOT NULL REFERENCES app."user"(id) ON DELETE CASCADE,
  role_id     SMALLINT  NOT NULL REFERENCES app.role(id)   ON DELETE RESTRICT,
  granted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, role_id)
);

-- route table
CREATE TABLE IF NOT EXISTS app.route (
  id     BIGSERIAL PRIMARY KEY,
  code   TEXT NOT NULL UNIQUE,
  name   TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT true
);

-- stop table
CREATE TABLE IF NOT EXISTS app.stop (
  id           BIGSERIAL PRIMARY KEY,
  name         TEXT NOT NULL,
  municipality TEXT,
  lat          NUMERIC(9,6) CHECK (lat BETWEEN -90 AND 90),
  lon          NUMERIC(9,6) CHECK (lon BETWEEN -180 AND 180),
  active       BOOLEAN NOT NULL DEFAULT true
);

-- route_stop table
CREATE TABLE IF NOT EXISTS app.route_stop (
  route_id      BIGINT   NOT NULL REFERENCES app.route(id) ON DELETE CASCADE,
  stop_id       BIGINT   NOT NULL REFERENCES app.stop(id)  ON DELETE RESTRICT,
  stop_sequence INTEGER  NOT NULL CHECK (stop_sequence > 0),
  dwell_time    INTERVAL,
  PRIMARY KEY (route_id, stop_id),
  UNIQUE (route_id, stop_sequence)
);

-- departure table
CREATE TABLE IF NOT EXISTS app.departure (
  id             BIGSERIAL PRIMARY KEY,
  route_id       BIGINT NOT NULL REFERENCES app.route(id) ON DELETE RESTRICT,
  planned_start  TIMESTAMPTZ NOT NULL,
  planned_end    TIMESTAMPTZ,
  vehicle_no     TEXT,
  status         dep_status NOT NULL DEFAULT 'PLANNED'
);

-- delay table
CREATE TABLE IF NOT EXISTS app.delay (
  id            BIGSERIAL PRIMARY KEY,
  departure_id  BIGINT NOT NULL REFERENCES app.departure(id) ON DELETE CASCADE,
  reported_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  delay_minutes INTEGER NOT NULL,
  reason        TEXT,
  severity      delay_severity NOT NULL,
  reported_by   BIGINT REFERENCES app."user"(id) ON DELETE SET NULL
);

-- ticket table
CREATE TABLE IF NOT EXISTS app.ticket (
  id            BIGSERIAL PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES app."user"(id)       ON DELETE RESTRICT,
  departure_id  BIGINT NOT NULL REFERENCES app.departure(id)     ON DELETE RESTRICT,
  qr_code_hash  TEXT NOT NULL UNIQUE,
  purchased_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  fare          fare_type NOT NULL,
  price_cents   INTEGER   NOT NULL CHECK (price_cents >= 0),
  state         ticket_state NOT NULL DEFAULT 'NEW'
);

-- Indexes
CREATE INDEX IF NOT EXISTS ix_user_role__role_id          ON app.user_role(role_id);
CREATE INDEX IF NOT EXISTS ix_route_stop__stop_id         ON app.route_stop(stop_id);
CREATE INDEX IF NOT EXISTS ix_departure__route_start      ON app.departure(route_id, planned_start);
CREATE INDEX IF NOT EXISTS ix_delay__dep_reported         ON app.delay(departure_id, reported_at DESC);
CREATE INDEX IF NOT EXISTS ix_ticket__user_purchased      ON app.ticket(user_id, purchased_at DESC);

