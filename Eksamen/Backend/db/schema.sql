-- Create transit schema
CREATE SCHEMA IF NOT EXISTS transit;
SET search_path TO transit, public;

-- Create transit ENUM types
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'service_day') THEN
    CREATE TYPE service_day AS ENUM ('WKD','SAT','SUN');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'direction') THEN
    CREATE TYPE direction AS ENUM ('OUTBOUND','INBOUND');
  END IF;
END$$;

-- line table
CREATE TABLE IF NOT EXISTS transit.line (
  id           SERIAL PRIMARY KEY,
  number       TEXT UNIQUE NOT NULL,
  name         TEXT NOT NULL,
  active_from  DATE DEFAULT DATE '2025-08-18',
  active_to    DATE DEFAULT DATE '2026-06-21'
);

-- transit.stop table
CREATE TABLE IF NOT EXISTS transit.stop (
  id     SERIAL PRIMARY KEY,
  name   TEXT NOT NULL UNIQUE,
  lat    NUMERIC(9,6),
  lon    NUMERIC(9,6)
);

-- line_stop table
CREATE TABLE IF NOT EXISTS transit.line_stop (
  line_id     INT NOT NULL REFERENCES transit.line(id) ON DELETE CASCADE,
  direction   direction NOT NULL,
  seq         INT NOT NULL,
  stop_id     INT NOT NULL REFERENCES transit.stop(id) ON DELETE RESTRICT,
  CONSTRAINT line_stop_pk PRIMARY KEY (line_id, direction, seq)
);

-- trip table
CREATE TABLE IF NOT EXISTS transit.trip (
  id          SERIAL PRIMARY KEY,
  line_id     INT NOT NULL REFERENCES transit.line(id) ON DELETE CASCADE,
  direction   direction NOT NULL,
  service     service_day NOT NULL,
  headsign    TEXT,
  notes       TEXT
);

-- stop_time table
CREATE TABLE IF NOT EXISTS transit.stop_time (
  trip_id     INT NOT NULL REFERENCES transit.trip(id) ON DELETE CASCADE,
  stop_id     INT NOT NULL REFERENCES transit.stop(id) ON DELETE RESTRICT,
  seq         INT NOT NULL,
  arrival     TIME NOT NULL,
  departure   TIME NOT NULL,
  CONSTRAINT stop_time_pk PRIMARY KEY (trip_id, stop_id)
);

-- Transit indexes
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='i' AND c.relname='idx_line_number' AND n.nspname='transit'
  ) THEN
    CREATE INDEX idx_line_number ON transit.line(number);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='i' AND c.relname='idx_stop_name' AND n.nspname='transit'
  ) THEN
    CREATE INDEX idx_stop_name ON transit.stop(name);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='i' AND c.relname='idx_trip_line' AND n.nspname='transit'
  ) THEN
    CREATE INDEX idx_trip_line ON transit.trip(line_id, service, direction);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='i' AND c.relname='idx_stop_time_trip_seq' AND n.nspname='transit'
  ) THEN
    CREATE INDEX idx_stop_time_trip_seq ON transit.stop_time(trip_id, seq);
  END IF;
END$$;

-- Transit constraints
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'stop_time_trip_seq_uniq'
  ) THEN
    ALTER TABLE transit.stop_time
      ADD CONSTRAINT stop_time_trip_seq_uniq UNIQUE (trip_id, seq);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'line_stop_unique_stop_per_dir'
  ) THEN
    ALTER TABLE transit.line_stop
      ADD CONSTRAINT line_stop_unique_stop_per_dir UNIQUE (line_id, direction, stop_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'line_stop_seq_pos'
  ) THEN
    ALTER TABLE transit.line_stop
      ADD CONSTRAINT line_stop_seq_pos CHECK (seq > 0);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'stop_time_seq_pos'
  ) THEN
    ALTER TABLE transit.stop_time
      ADD CONSTRAINT stop_time_seq_pos CHECK (seq > 0);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'stop_time_time_order'
  ) THEN
    ALTER TABLE transit.stop_time
      ADD CONSTRAINT stop_time_time_order CHECK (departure >= arrival);
  END IF;
END$$;

-- Transit view
CREATE OR REPLACE VIEW transit.vw_rutetider AS
SELECT 
  l.number AS linje_nr,
  l.name   AS linje_navn,
  t.id     AS trip_id,
  t.service,
  t.direction,
  s.name   AS stopp,
  st.arrival,
  st.departure,
  st.seq
FROM transit.line l
JOIN transit.trip t       ON t.line_id = l.id
JOIN transit.stop_time st ON st.trip_id = t.id
JOIN transit.stop s       ON s.id = st.stop_id
ORDER BY l.number, t.id, st.seq;

